using System.Collections.Generic;

using UnityEngine;
using UnityEngine.Rendering;

#if UNITY_EDITOR
    using UnityEditor;
    using UnityEditor.SceneManagement;
#endif


namespace Sinnwrig.FogVolumes
{
    /// <summary>
    /// Authoring component for a fog volume.
    /// <para>The volume is rendered by a regular <see cref="MeshRenderer"/> using a material that this component keeps in sync with its
    /// settings and profile. The renderer and material are serialized with the scene, so the fog keeps rendering where this component
    /// cannot run (in VRChat it is stripped on upload).</para>
    /// </summary>
    [ExecuteAlways]
    [DisallowMultipleComponent]
    [RequireComponent(typeof(MeshFilter), typeof(MeshRenderer))]
    [HelpURL("https://github.com/Hoppou-Legion-Gateway/BIRP-Fog-Volumes/blob/main/README.md")]
    public class FogVolume : MonoBehaviour
#if FOGVOLUMES_VRCSDK
        , VRC.SDKBase.IEditorOnly
#endif
    {
        /// <summary>
        /// The rendered shape of the volume.
        /// </summary>
        public VolumeType volumeType;

        /// <summary>
        /// How intensely the volume should fade from its edges determined by a nonlinear, normalized range.
        /// <para>Cube volumes use the [x, y, z] components for each local axis.</para>
        /// <para>Cylinder volumes use the [x, y] components for radius and height.</para>
        /// <para>Capsule and Sphere volumes use the [x] components for radius.</para>
        /// </summary>
        public Vector3 edgeFade = Vector3.one * 0.6f;

        /// <summary>
        /// The offset applied to the volume to determine where fading begins/ends.
        /// <para>Cube volumes use the [x, y, z] components in the range [-0.5, 0.5] to offset each local axis.</para>
        /// <para>Cylinder volumes use the [y] component in the range [-1, 1] for height offset.</para>
        /// <para>Capsule and Sphere volumes ignore this setting.</para>
        /// </summary>
        public Vector3 fadeOffset = Vector3.zero;

        /// <summary>
        /// Determines whether or not fog lighting will be affected by fading along with base fog albedo.
        /// </summary>
        public bool lightsFade = false;

        /// <summary>
        /// The maximum render distance of the fog.
        /// </summary>
        [Min(0)]
        public float maxDistance = 100.0f;

        /// <summary>
        /// The percentage from the maximum distance at which to begin fading fog.
        /// </summary>
        [Range(0, 1f)]
        public float distanceFade = 1f;


        private FogVolumeProfile _internalProfile;

        /// <summary>
        /// The shared profile used by this volume.
        /// </summary>
        public FogVolumeProfile sharedProfile = null;

        /// <summary>
        /// The instantiated profile used by this volume.
        /// </summary>
        public FogVolumeProfile profile
        {
            get
            {
                if (_internalProfile == null)
                {
                    if (sharedProfile != null)
                        _internalProfile = Instantiate(sharedProfile);
                }

                return _internalProfile;
            }

            set => _internalProfile = value;
        }


        /// <summary>
        /// Is this volume using a shared profile or an instantiated one?
        /// </summary>
        public bool HasInstantiatedProfile() => _internalProfile != null;


        /// <summary>
        /// (Read-Only) The profile currently being used by this volume.
        /// </summary>
        public FogVolumeProfile ProfileReference => _internalProfile == null ? sharedProfile : _internalProfile;


        /// <summary>
        /// (Read-Only) The material this volume renders with. It is owned by the volume and rewritten whenever the volume or its profile changes.
        /// </summary>
        public Material Material => material;


        private const string shaderName = "Fog Volumes/Volumetric Fog";

        [SerializeField, HideInInspector] private Shader shader;
        [SerializeField, HideInInspector] private Material material;

        private MeshFilter meshFilter;
        private MeshRenderer meshRenderer;

        // Duplicating a volume shares its scene-embedded material with the copy. Track owners so each volume gets its own.
        private static readonly Dictionary<Material, FogVolume> materialOwners = new();

        // Material keywords generated by the [KeywordEnum] _Shape property of the fog shader
        private static readonly string[] shapeKeywords = VolumeTypeExtensions.shapeKeywords;


        private void Reset()
        {
            shader = Shader.Find(shaderName);
        }


        private void OnEnable()
        {
            FogVolumeProfile.Changed += OnProfileChanged;
            UpdateVolume();
        }


        private void OnDisable()
        {
            FogVolumeProfile.Changed -= OnProfileChanged;

            if (material != null && materialOwners.TryGetValue(material, out FogVolume owner) && owner == this)
                materialOwners.Remove(material);

            if (meshRenderer != null)
                meshRenderer.enabled = false;
        }


        private void OnValidate()
        {
            // Components can't be added or modified from inside OnValidate, defer the update
#if UNITY_EDITOR
            EditorApplication.delayCall += DelayedUpdate;
#endif
        }


        private void OnProfileChanged(FogVolumeProfile changed)
        {
            if (changed != ProfileReference)
                return;

#if UNITY_EDITOR
            EditorApplication.delayCall += DelayedUpdate;
#else
            UpdateVolume();
#endif
        }


        private void DelayedUpdate()
        {
            if (this != null && isActiveAndEnabled)
                UpdateVolume();
        }


        // Pick up runtime changes made to the volume or its profile by scripts and animations
        private void LateUpdate()
        {
            if (Application.isPlaying)
                UpdateVolume();
        }


        // The fog shader needs the camera depth texture to clip fog against the scene
        private void OnWillRenderObject()
        {
            Camera camera = Camera.current;

            if (camera != null && (camera.depthTextureMode & DepthTextureMode.Depth) == 0)
                camera.depthTextureMode |= DepthTextureMode.Depth;
        }


        /// <summary>
        /// Synchronizes the renderer and material with the volume and profile settings.
        /// This is done automatically when either changes in the editor, and every frame in play mode.
        /// </summary>
        public void UpdateVolume()
        {
            bool changed = EnsureMaterial();

            if (material == null)
                return;

            changed |= SetupRenderer();
            changed |= SetupVolumeProperties();

            FogVolumeProfile profileReference = ProfileReference;

            if (profileReference != null)
                changed |= profileReference.ApplyTo(material);

            // Volumes without a profile don't render
            meshRenderer.enabled = profileReference != null;

#if UNITY_EDITOR
            if (changed && !Application.isPlaying)
            {
                // Make sure the change reaches the saved scene, which is what gets built or uploaded
                EditorUtility.SetDirty(material);
                EditorUtility.SetDirty(this);
            }
#endif
        }


        private bool EnsureMaterial()
        {
            if (shader == null)
                shader = Shader.Find(shaderName);

            if (shader == null)
            {
                Debug.LogError($"Could not find the '{shaderName}' shader. Fog volume '{name}' will not render.", this);
                return false;
            }

            bool changed = false;

            if (material != null && materialOwners.TryGetValue(material, out FogVolume owner) && owner != null && owner != this)
                material = null;

            if (material == null)
            {
                material = new Material(shader) { name = name + " (Fog Volume)" };

#if UNITY_EDITOR
                // Prefab assets can't store embedded materials. Instances placed in a scene create and save their own.
                if (EditorUtility.IsPersistent(gameObject) || PrefabStageUtility.GetPrefabStage(gameObject) != null)
                    material.hideFlags = HideFlags.DontSave;
#endif

                changed = true;
            }
            else if (material.shader != shader)
            {
                material.shader = shader;
                changed = true;
            }

            materialOwners[material] = this;

            return changed;
        }


        private bool SetupRenderer()
        {
            bool changed = false;

            if (meshFilter == null && !TryGetComponent(out meshFilter))
            {
                meshFilter = gameObject.AddComponent<MeshFilter>();
                changed = true;
            }

            if (meshRenderer == null && !TryGetComponent(out meshRenderer))
            {
                meshRenderer = gameObject.AddComponent<MeshRenderer>();
                changed = true;
            }

            Mesh mesh = volumeType.GetProxyMesh();
            if (meshFilter.sharedMesh != mesh)
            {
                meshFilter.sharedMesh = mesh;
                changed = true;
            }

            if (meshRenderer.sharedMaterial != material)
            {
                meshRenderer.sharedMaterial = material;
                changed = true;
            }

            if (meshRenderer.shadowCastingMode != ShadowCastingMode.Off)
            {
                meshRenderer.shadowCastingMode = ShadowCastingMode.Off;
                changed = true;
            }

            // Required for point and spot light shadows to be sampled in the per-light passes
            if (!meshRenderer.receiveShadows)
            {
                meshRenderer.receiveShadows = true;
                changed = true;
            }

            if (meshRenderer.lightProbeUsage != LightProbeUsage.Off)
            {
                meshRenderer.lightProbeUsage = LightProbeUsage.Off;
                changed = true;
            }

            if (meshRenderer.reflectionProbeUsage != ReflectionProbeUsage.Off)
            {
                meshRenderer.reflectionProbeUsage = ReflectionProbeUsage.Off;
                changed = true;
            }

            if (meshRenderer.motionVectorGenerationMode != MotionVectorGenerationMode.ForceNoMotion)
            {
                meshRenderer.motionVectorGenerationMode = MotionVectorGenerationMode.ForceNoMotion;
                changed = true;
            }

#if UNITY_EDITOR
            // Static batching bakes the transform the raymarcher relies on into the mesh,
            // a volume baked as an occluder hides what's behind it, and fog shouldn't contribute to baked lighting.
            const StaticEditorFlags unsupportedFlags = StaticEditorFlags.BatchingStatic | StaticEditorFlags.OccluderStatic | StaticEditorFlags.ContributeGI;
            StaticEditorFlags flags = GameObjectUtility.GetStaticEditorFlags(gameObject);

            if ((flags & unsupportedFlags) != 0)
            {
                GameObjectUtility.SetStaticEditorFlags(gameObject, flags & ~unsupportedFlags);
                changed = true;
            }
#endif

            return changed;
        }


        private bool SetupVolumeProperties()
        {
            var writer = new MaterialWriter(material);

            writer.SetFloat("_Shape", (int)volumeType);
            for (int i = 0; i < shapeKeywords.Length; i++)
                writer.SetKeyword(shapeKeywords[i], i == (int)volumeType);

            writer.SetVector("_EdgeFade", edgeFade);
            writer.SetVector("_FadeOffset", fadeOffset);
            writer.SetFloat("_LightsFade", lightsFade ? 1 : 0);

            writer.SetFloat("_MaxDistance", maxDistance);
            writer.SetFloat("_DistanceFade", distanceFade);

            return writer.Changed;
        }


        /// <summary>
        /// Determines if the volume should be culled given a camera position and the camera culling planes
        /// </summary>
        /// <param name="cameraPosition">The position of the camera to use in determining culling state.</param>
        /// <param name="cameraPlanes">The camera planes to use in determining culling state.</param>
        /// <returns>True if the volume shoud be culled, false otherwise.</returns>
        public bool CullVolume(Vector3 cameraPosition, Plane[] cameraPlanes)
        {
            if (ProfileReference == null)
                return true;

            Bounds aabb = GetAABB();

            // Volume is past maximum distance
            if ((cameraPosition - aabb.ClosestPoint(cameraPosition)).sqrMagnitude > maxDistance * maxDistance)
                return true;

            // Volume is outside camera frustum
            if (!GeometryUtility.TestPlanesAABB(cameraPlanes, aabb))
                return true;

            return false;
        }


        /// <returns>The local-space culling bounds of the volume</returns>
        public Bounds GetBounds()
        {
            if (volumeType == VolumeType.Capsule || volumeType == VolumeType.Cylinder)
                return BoundsUtility.capsuleBounds;

            // Default to cube
            return BoundsUtility.cubeBounds;
        }


        /// <returns>The world-space Axis-Aligned Bounds of the volume</returns>
        public Bounds GetAABB()
        {
            if (volumeType == VolumeType.Capsule || volumeType == VolumeType.Cylinder)
                return GeometryUtility.CalculateBounds(BoundsUtility.capsuleCorners, transform.localToWorldMatrix);

            // Default to cube
            return GeometryUtility.CalculateBounds(BoundsUtility.cubeCorners, transform.localToWorldMatrix);
        }
    }
}
