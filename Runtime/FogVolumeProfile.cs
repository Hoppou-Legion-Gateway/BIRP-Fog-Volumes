using UnityEngine;


namespace Sinnwrig.FogVolumes
{
    /// <summary>How light should affect fog volumes.</summary>
    [System.Serializable]
    public enum LightingMode
    {
        /// <summary>
        /// Lights do not affect the volume
        /// </summary>
        Unlit,

        /// <summary>
        /// Only lights affect the volume
        /// </summary>
        Lit,

        /// <summary>
        /// Lights and shadows affect the volume. In the built-in pipeline only point and spot light shadows can be sampled.
        /// </summary>
        Shadowed
    }

    [CreateAssetMenu(menuName = "Fog Volumes/Volume Profile")]
    [HelpURL("https://github.com/Hoppou-Legion-Gateway/BIRP-Fog-Volumes/blob/main/README.md")]
    public class FogVolumeProfile : ScriptableObject
    {
        /// <summary>
        /// The ambient color of the fog when not lit.
        /// </summary>
        [ColorUsage(false, true)]
        public Color ambientColor = Color.white;

        /// <summary>
        /// How strongly the fog obscures the background behind it. A value of 0 will be only additive. Values higher than 0 will allow fog to influence background color based on density. 
        /// </summary>
        public float ambientOpacity = 1;

        /// <summary>
        /// The base (multiplicative) color of the fog.
        /// </summary>
        [ColorUsage(false, true)]
        public Color albedo = Color.white;



        /// <summary>
        /// The thresholds for the step length taken by the raymarcher. Minimum step length is stored in the [x] component. Maximum step length is stored in the [y] component. 
        /// </summary>
        public Vector2 minMaxStepLength = new(0.5f, 3f);

        /// <summary>
        /// The factor at which the step length taken by the raymarcher is increased.
        /// </summary>
        [Range(1, 2)]
        public float stepIncrementFactor = 1.1f;

        /// <summary>
        /// The maximum total length of a ray.
        /// </summary>
        [Min(0)]
        public float maxRayLength = 50.0f;

        /// <summary>
        /// The maximum amount of samples or steps the raymarcher is allowed to take.
        /// </summary>
        [Range(1, 1024)]
        public int maxSampleCount = 36;

        /// <summary>
        /// The intensity of pseudorandom jitter used to offset the starting point of the raymarcher.
        /// </summary>
        public float jitterStrength = 0.05f;



        /// <summary>
        /// The lighting mode of the fog.
        /// </summary>
        public LightingMode lightingMode = LightingMode.Lit;

        /// <summary>
        /// Modulates the strength and intensity of the lights affecting the fog.
        /// </summary>
        [Min(0)]
        public float lightIntensityModifier = 1;

        /// <summary>
        /// How much light is scattered towards the camera. Higher values will produce brighter fog.
        /// </summary>
        [Range(0, 1)]
        public float scattering = 0.1f;

        /// <summary>
        /// How quickly light power is reduced based on its distance to the camera. Higher values will fade fog further away.
        /// </summary>
        [Range(0, 1)]
        public float extinction = 0.05f;

        /// <summary>
        /// Determines the distribution of scattered light based on the viewing angle. Higher values will increase how strongly brightness is focused on light position.
        /// </summary>
        [Range(0, 0.999f)]
        public float mieG = 0.1f;

        /// <summary>
        /// The value at which the brightness of the fog will be clamped.
        /// </summary>
        [Range(0, 100)]
        public float brightnessClamp = 10f;



        /// <summary>
        /// The world-space noise to apply to the fog volume.
        /// </summary>
        public Texture3D noiseTexture;

        /// <summary>
        /// The scale of the noise texture.
        /// </summary>
        [Min(0)]
        public float scale = 0.1f;

        /// <summary>
        /// The direction in which the noise should scroll.
        /// </summary>
        public Vector3 noiseScroll = new(0, -0.15f, 0);

        /// <summary>
        /// How intensely the noise will affect the fog.
        /// </summary>
        [Range(0, 1)]
        public float noiseIntensity = 1;

        /// <summary>
        /// The offset applied to the noise texture values.
        /// </summary>
        [Range(0, 1)]
        public float intensityOffset = 0.5f;



        /// <summary>
        /// Invoked when any profile is modified in the inspector, so volumes using it can refresh their materials.
        /// </summary>
        internal static event System.Action<FogVolumeProfile> Changed;

        private void OnValidate() => Changed?.Invoke(this);


        // Material keywords generated by the [KeywordEnum] _Lighting property of the fog shader
        private static readonly string[] lightingKeywords = new string[]
        {
            "_LIGHTING_UNLIT",
            "_LIGHTING_LIT",
            "_LIGHTING_SHADOWED"
        };


        /// <summary>
        /// Copies the profile settings into a material using the fog volume shader.
        /// </summary>
        /// <param name="material">The material to write to.</param>
        /// <returns>True if any material value changed.</returns>
        public bool ApplyTo(Material material)
        {
            var writer = new MaterialWriter(material);

            SetupLighting(ref writer);
            SetupNoise(ref writer);

            return writer.Changed;
        }


        private void SetupNoise(ref MaterialWriter writer)
        {
            writer.SetKeyword("_FOG_NOISE", noiseTexture != null);
            writer.SetFloat("_NoiseEnabled", noiseTexture != null ? 1 : 0);

            writer.SetTexture("_NoiseTexture", noiseTexture);
            writer.SetFloat("_NoiseScale", scale);
            writer.SetVector("_NoiseScroll", noiseScroll);
            writer.SetFloat("_NoiseIntensity", noiseIntensity);
            writer.SetFloat("_NoiseIntensityOffset", intensityOffset);
        }


        private void SetupLighting(ref MaterialWriter writer)
        {
            writer.SetVector("_Ambient", ambientColor);
            writer.SetFloat("_AmbientOpacity", ambientOpacity);

            writer.SetVector("_Albedo", albedo);

            writer.SetFloat("_IntensityModifier", lightIntensityModifier);

            writer.SetFloat("_MinStepLength", minMaxStepLength.x);
            writer.SetFloat("_MaxStepLength", minMaxStepLength.y);
            writer.SetFloat("_StepIncrement", stepIncrementFactor);
            writer.SetFloat("_MaxRayLength", maxRayLength);
            writer.SetFloat("_SampleCount", maxSampleCount);
            writer.SetFloat("_Jitter", jitterStrength);

            writer.SetFloat("_MieG", mieG);
            writer.SetFloat("_Scattering", scattering);
            writer.SetFloat("_Extinction", extinction);

            writer.SetFloat("_BrightnessClamp", brightnessClamp);

            writer.SetFloat("_Lighting", (int)lightingMode);
            for (int i = 0; i < lightingKeywords.Length; i++)
                writer.SetKeyword(lightingKeywords[i], i == (int)lightingMode);

            // Skip the per-light passes entirely when lights can't affect the fog
            writer.SetPassEnabled("ForwardAdd", lightingMode != LightingMode.Unlit);
        }
    }
}